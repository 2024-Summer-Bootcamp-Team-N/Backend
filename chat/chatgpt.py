# aioredis 연결
redis_client = aioredis.from_url(f"redis://{settings.REDIS_HOST}:{settings.REDIS_PORT}/{settings.REDIS_DB}")

@sync_to_async
def get_database_info(room_id=None):
    try:
        RoomDetailInfo = apps.get_model('options', 'RoomDetailInfo')

        if room_id:
            room_detail_info = RoomDetailInfo.objects.filter(room_id=room_id).first()

            if room_detail_info:
                info = f"Room Information (ID: {room_id}):\n"
                for field in room_detail_info._meta.fields:
                    info += f"- {field.name}: {getattr(room_detail_info, field.name)}\n"
            else:
                info = f"No information found for room_id {room_id}"
        else:
            info = "Sample Room Information:\n"
            for room in RoomDetailInfo.objects.all()[:5]:
                info += f"- Room ID: {room.room_id}\n"
                info += f"  {room}\n"

        return info
    except Exception as e:
        return f"데이터베이스 정보 조회 중 오류 발생: {str(e)}"

